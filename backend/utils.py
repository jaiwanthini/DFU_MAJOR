# 2. Standardized API Responses
# ==========================================================
def format_success(
    data: Any, 
    message: str = "Success", 
    status_code: int = 200, 
    include_timestamp: bool = False
) -> Tuple[Dict[str, Any], int]:
    """
    Wraps API success output in a standardized envelope.
    
    Returns
    -------
    Tuple[dict, int]
        Flask-compatible JSON dictionary and HTTP status code.
    """
    response: Dict[str, Any] = {
        "status": "success",
        "message": message
    }
    
    if include_timestamp:
        response["timestamp"] = datetime.now().isoformat()
        
    response["data"] = data
    
    return response, status_code

def format_error(
    message: str, 
    error_code: int = 400, 
    details: Optional[Any] = None,
    error_type: Optional[str] = None,
    include_timestamp: bool = False
) -> Tuple[Dict[str, Any], int]:
    """
    Wraps API errors in a standardized envelope.
    
    Returns
    -------
    Tuple[dict, int]
        Flask-compatible JSON dictionary and HTTP error status code.
    """
    response: Dict[str, Any] = {
        "status": "error",
        "message": message
    }
    
    if error_type:
        response["error_type"] = error_type
        
    if include_timestamp:
        response["timestamp"] = datetime.now().isoformat()
        
    if details:
        response["details"] = details
        
    return response, error_code


