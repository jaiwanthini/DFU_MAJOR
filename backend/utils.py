# 4. Dictionary Validation Helpers
# ==========================================================
def get_missing_keys(payload: Dict[str, Any], required_keys: Iterable[str]) -> List[str]:
    """
    Validates that a dictionary contains all required keys.
    
    Returns
    -------
    list
        A list of missing string keys. Empty if all are present.
    """
    if not isinstance(required_keys, (list, set, tuple)):
        raise TypeError("required_keys must be an iterable (e.g., list or tuple).")
        
    if not isinstance(payload, dict):
        return list(required_keys)
        
    return [key for key in required_keys if key not in payload]

def validate_required_keys(payload: Dict[str, Any], required_keys: Iterable[str]) -> None:
    """
    Validates that a dictionary contains all required keys.
    Raises a ValueError if any keys are missing.
    
    Parameters
    ----------
    payload : dict
        The dictionary to validate.
    required_keys : iterable
        A list of expected string keys.
        
    Raises
    ------
    ValueError
        If any required keys are missing.
    """
    missing_keys = get_missing_keys(payload, required_keys)
    if missing_keys:
        raise ValueError(f"Missing required keys: {', '.join(missing_keys)}")
    return None
